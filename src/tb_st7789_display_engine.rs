/// Implements a maximum length sequence Linear Feedback Shift Register (LFSR) in Galois form for a `u16`.
///
/// # Arguments
///
/// * `x` - A mutable reference to the current state of the LFSR.
///
/// # Description
///
/// This function updates the LFSR state in-place using a feedback polynomial.
/// The feedback polynomial used here is `x^16 + x^14 + x^13 + x^11 + 1`, which is known to generate
/// a maximum length sequence for a 16-bit LFSR.
fn lfsr_16(x: &mut u16) {
    // Extract the least significant bit (LSB) as the feedback bit.
    let lsb = *x & 1;
    // Right shift the register by 1.
    *x >>= 1;
    // Apply the feedback polynomial if the LSB was 1.
    if lsb == 1 {
        *x ^= 0xB400; // Feedback polynomial: x^16 + x^14 + x^13 + x^11 + 1
    }
}

/// Testbench function for the ST7789 display engine.
///
/// # Arguments
///
/// * `peripherals` - The peripherals object provided by the ESP HAL.
///
/// # Description
///
/// This function initializes the ST7789 display engine, sets up the SPI pins, and performs a test loop
/// that continuously fills the screen with colors generated by an LFSR. It also measures and prints
/// the render time for each frame.
pub fn tb_st7789_display_engine(peripherals: Peripherals) -> ! {
    esp_println::println!("Defining pins...");
    // Define the backlight pin (GPIO32).
    let _blk = Output::new(
        peripherals.GPIO32,
        esp_hal::gpio::Level::High,
        OutputConfig::default().with_pull(esp_hal::gpio::Pull::Up),
    );
    // Define input pins for diodes (GPIO12 and GPIO13).
    let _diode_a = Input::new(peripherals.GPIO12, InputConfig::default());
    let _diode_b = Input::new(peripherals.GPIO13, InputConfig::default());

    let lcd_height = 240;
    let lcd_width = 135;

    esp_println::println!("Defining spi pins...");
    // Define the SPI pins for the display.
    let pins = SpiPinsMaster {
        mosi: Output::new(
            peripherals.GPIO23,
            esp_hal::gpio::Level::Low,
            OutputConfig::default().with_pull(esp_hal::gpio::Pull::Down),
        ),
        miso: None,
        sclk: Output::new(
            peripherals.GPIO18,
            esp_hal::gpio::Level::Low,
            OutputConfig::default().with_pull(esp_hal::gpio::Pull::Down),
        ),
        cs: Output::new(
            peripherals.GPIO15,
            esp_hal::gpio::Level::High,
            OutputConfig::default().with_pull(esp_hal::gpio::Pull::Up),
        ),
        dc: Some(Output::new(
            peripherals.GPIO2,
            esp_hal::gpio::Level::High,
            OutputConfig::default().with_pull(esp_hal::gpio::Pull::Up),
        )),
        rst: Some(Output::new(
            // Active low reset pin (GPIO4).
            peripherals.GPIO4,
            esp_hal::gpio::Level::High,
            OutputConfig::default().with_pull(esp_hal::gpio::Pull::Down),
        )),
    };

    esp_println::println!("Defining screen manager...");
    // Initialize the display engine with the SPI pins and screen dimensions.
    let mut screen = St7789DisplayEngine::new(pins, lcd_width, lcd_height);

    esp_println::println!("Initialize...");
    // Send the initialization sequence to the display.
    screen.display_initialization_sequence();

    esp_println::println!("Rotation...");
    // Set the display rotation to mode 2.
    screen.set_rotation(2);

    esp_println::println!("Display Colors...");
    screen.fill_screen(ST77XX_BLACK);
    let mut color: u16 = ST77XX_GREEN;
    const shape_size: u16 = 25;

    // Main loop: continuously fill the screen with colors generated by the LFSR.
    loop {
        let start_time = Instant::now();

        // Update the color using the LFSR.
        lfsr_16(&mut color);

        // Fill the screen with the generated color.
        if color % 3 == 0 {
            screen.fill_regular_polygon(
                color % lcd_width,
                color % lcd_height,
                color % shape_size,
                (color % 180) as f32,
                3 + color % 5,
                color,
            );
        }
        if color % 3 == 1 {
            screen.fill_circle(
                color % lcd_width,
                color % lcd_height,
                color % shape_size,
                color,
            );
        }
        if color % 3 == 2 {
            screen.fill_rectangle(
                color % lcd_width,
                color % lcd_height,
                color % shape_size,
                color % shape_size,
                color,
            );
        }

        // Print the render time for the current frame.
        esp_println::println!(
            "Render time: { } seconds",
            start_time.elapsed().as_micros() as f64 / 1E6
        );

        // Wait for 1 second before rendering the next frame.
        while start_time.elapsed() < esp_hal::time::Duration::from_millis(100) {}
    }
}
